/**
 *
 * Programa que hace el cuadrado de un número y lo muestra por pantalla.
 * 
 * @author israel
 */
public class Ejercicio11 {

    /**
     * @param args the command line arguments
     */
    public static void main(String[] args) {
        
        // Incializo la variable numero
        int numero = 2;
        
        // Incializo la variable cuad y establezo una operación
        int cuad = numero * numero;
        
        // Muestro por pantalla la operación
        System.out.println("EL CUADRADO DE " + numero + " ES " + cuad);
    }
}