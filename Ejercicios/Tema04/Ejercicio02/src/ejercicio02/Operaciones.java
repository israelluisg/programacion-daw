public class Operaciones {
    
    /**
     * Método que multiplica dos números y muestra el resultado por pantalla.
     * @param num1
     * @param num2
     */
    public static void multiplicar (int num1, int num2) {
        System.out.println("La operación que se realizó es producto y el resultado es: " 
                    + (num1 * num2));
    }
    
    /**
     * Método que suma dos números y muestra el resultado por pantalla.
     * @param num1
     * @param num2
     */
    public static void sumar (int num1, int num2) {
        System.out.println("La operación que se realizó es suma y el resultado es: " 
                    + (num1 + num2));
    }
}
